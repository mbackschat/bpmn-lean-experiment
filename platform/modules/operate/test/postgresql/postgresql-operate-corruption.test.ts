import assert from "node:assert/strict";
import { after, before, beforeEach, test } from "node:test";

import {
  PostgresqlExecutionPublicationRepository,
  PostgresqlFlowNodeOccurrenceRepository,
  PostgresqlIncidentActionRepository,
  PostgresqlProcessInstanceRepository,
} from "@bpmn-lean/platform-operate";
import type { PostgresqlRuntime } from "@bpmn-lean/platform-postgresql-runtime";

import {
  firstPage,
  registration,
  secondPage,
} from "../execution-publication-fixture.ts";
import {
  occurrenceFirstPage,
  occurrenceRegistration,
  occurrenceSecondPage,
} from "../flow-node-occurrence-fixture.ts";
import {
  incidentAudit,
  incidentBinding,
} from "../support/incident-action-repository-contract.ts";
import {
  processPublication,
} from "../support/process-instance-repository-contract.ts";
import {
  createOperateTestRuntime,
  migrateOperateDatabase,
  resetOperateDatabase,
} from "./postgresql-operate-test-support.ts";

const baseUrl = process.env.BPMN_TEST_POSTGRES_URL;

if (baseUrl === undefined) {
  test("PostgreSQL Operate corruption probes require the explicit real-database witness", {
    skip: "BPMN_TEST_POSTGRES_URL is not set",
  });
} else {
  const runtime = createOperateTestRuntime(baseUrl, "operate-corruption", 16);

  before(async () => await migrateOperateDatabase(baseUrl));
  beforeEach(async () => await resetOperateDatabase(runtime));
  after(async () => await runtime.close());

  test("Process identity canonical, redundant, unsafe-bigint, and state corruption fails closed", async () => {
    const repository = new PostgresqlProcessInstanceRepository(runtime);
    const publication = processPublication("corrupt-process");
    await repository.recordConfirmed(publication);
    const encodedId = Buffer.from(publication.instance.processInstanceId, "utf8");
    const canonical = JSON.stringify(publication.instance);

    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_process_instances
        SET public_identity_json = $1
        WHERE process_instance_id = $2
      `,
      values: [` ${canonical}`, encodedId],
    });
    await assert.rejects(repository.getRegistration("corrupt-process"), {
      name: "ProcessInstanceStoredValueError",
    });
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_process_instances
        SET public_identity_json = $1, process_id = $2
        WHERE process_instance_id = $3
      `,
      values: [canonical, Buffer.from("changed", "utf8"), encodedId],
    });
    await assert.rejects(repository.getRegistration("corrupt-process"), {
      name: "ProcessInstanceStoredValueError",
    });
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_process_instances
        SET process_id = $1
        WHERE process_instance_id = $2
      `,
      values: [Buffer.from(publication.instance.definition.processId, "utf8"), encodedId],
    });

    await runtime.query({
      text: `
        ALTER TABLE bpmn_platform.operate_process_instances
        DROP CONSTRAINT operate_process_instances_ordinal_check
      `,
    });
    await runtime.query({
      text: `
        ALTER TABLE bpmn_platform.operate_process_instances
        ALTER COLUMN ordinal SET GENERATED BY DEFAULT
      `,
    });
    try {
      await runtime.query({
        text: `
          UPDATE bpmn_platform.operate_process_instances
          SET ordinal = 9007199254740992
          WHERE process_instance_id = $1
        `,
        values: [encodedId],
      });
      await assert.rejects(repository.getRegistration("corrupt-process"), {
        name: "ProcessInstanceStoredValueError",
      });
    } finally {
      await runtime.query({
        text: `
          UPDATE bpmn_platform.operate_process_instances
          SET ordinal = 1
          WHERE process_instance_id = $1
        `,
        values: [encodedId],
      });
      await runtime.query({
        text: `
          ALTER TABLE bpmn_platform.operate_process_instances
          ADD CONSTRAINT operate_process_instances_ordinal_check CHECK (
            ordinal > 0 AND ordinal <= 9007199254740991
          )
        `,
      });
      await runtime.query({
        text: `
          ALTER TABLE bpmn_platform.operate_process_instances
          ALTER COLUMN ordinal SET GENERATED ALWAYS
        `,
      });
    }

    await runtime.query({
      text: `
        ALTER TABLE bpmn_platform.operate_process_instances
        DROP CONSTRAINT operate_process_instances_observation_check
      `,
    });
    try {
      await runtime.query({
        text: `
          UPDATE bpmn_platform.operate_process_instances
          SET observation = 'broken'
          WHERE process_instance_id = $1
        `,
        values: [encodedId],
      });
      await assert.rejects(repository.getRegistration("corrupt-process"), {
        name: "ProcessInstanceStoredValueError",
      });
    } finally {
      await runtime.query({
        text: `
          UPDATE bpmn_platform.operate_process_instances
          SET observation = 'active'
          WHERE process_instance_id = $1
        `,
        values: [encodedId],
      });
      await runtime.query({
        text: `
          ALTER TABLE bpmn_platform.operate_process_instances
          ADD CONSTRAINT operate_process_instances_observation_check CHECK (
            observation IN ('active', 'closed', 'indeterminate')
          )
        `,
      });
    }
  });

  test("incident binding and audit-event canonical corruption fails closed", async () => {
    const processes = new PostgresqlProcessInstanceRepository(runtime);
    const incidents = new PostgresqlIncidentActionRepository(runtime);
    await processes.recordConfirmed(
      processPublication("incident-instance", "Incident_Process"),
    );
    const binding = incidentBinding("corrupt-action");
    await incidents.reserve(binding, incidentAudit(binding, "reserved"));
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_incident_actions
        SET binding_json = ' ' || binding_json
        WHERE action_id = $1
      `,
      values: [Buffer.from(binding.actionId, "utf8")],
    });
    await assert.rejects(incidents.get(binding.actionId), {
      name: "OperateIncidentStoredValueError",
    });
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_incident_action_audit_outbox
        SET event_json = ' ' || event_json
        WHERE event_id = $1
      `,
      values: [Buffer.from(incidentAudit(binding, "reserved").eventId, "utf8")],
    });
    await assert.rejects(incidents.listUndeliveredAuditEvents(), {
      name: "OperateIncidentStoredValueError",
    });
  });

  test("E1 header and batch canonical or redundant corruption fails closed", async () => {
    const { repository, processInstanceId } = await prepareExecution();
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_execution_publications
        SET identity_json = ' ' || identity_json
        WHERE process_instance_id = $1
      `,
      values: [Buffer.from(processInstanceId, "utf8")],
    });
    await assert.rejects(repository.get(processInstanceId), {
      name: "ExecutionPublicationStoredValueError",
    });
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_execution_publications
        SET identity_json = ltrim(identity_json)
        WHERE process_instance_id = $1
      `,
      values: [Buffer.from(processInstanceId, "utf8")],
    });
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_execution_publication_batches
        SET command_id = $1
        WHERE process_instance_id = $2 AND from_revision = 0
      `,
      values: [Buffer.from("changed-command", "utf8"), Buffer.from(processInstanceId, "utf8")],
    });
    await assert.rejects(repository.get(processInstanceId), {
      name: "ExecutionPublicationStoredValueError",
    });
  });

  test("occurrence batch and row corruption fails closed and one get uses one query", async () => {
    const { repository, processInstanceId } = await prepareOccurrence();
    let queryCount = 0;
    const countedRuntime: PostgresqlRuntime = {
      query: async (query: Parameters<typeof runtime.query>[0]) => {
        queryCount += 1;
        return await runtime.query(query);
      },
      transaction: async (run) => await runtime.transaction(run),
      withDedicatedSession: async (run) => await runtime.withDedicatedSession(run),
      databaseClockEpochMs: async () => await runtime.databaseClockEpochMs(),
      close: async () => await runtime.close(),
    };
    assert.equal(
      (await new PostgresqlFlowNodeOccurrenceRepository(countedRuntime)
        .get(processInstanceId))?.headRevision,
      3,
    );
    assert.equal(queryCount, 1);
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_flow_node_occurrence_batches
        SET command_id = $1
        WHERE process_instance_id = $2 AND from_revision = 0
      `,
      values: [Buffer.from("changed-command", "utf8"), Buffer.from(processInstanceId, "utf8")],
    });
    await assert.rejects(repository.get(processInstanceId), {
      name: "FlowNodeOccurrenceStoredValueError",
    });
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_flow_node_occurrence_batches
        SET command_id = $1
        WHERE process_instance_id = $2 AND from_revision = 0
      `,
      values: [Buffer.from("command-start", "utf8"), Buffer.from(processInstanceId, "utf8")],
    });
    await runtime.query({
      text: `
        UPDATE bpmn_platform.operate_flow_node_occurrences
        SET occurrence_json = ' ' || occurrence_json
        WHERE hosting_process_instance_id = $1
      `,
      values: [Buffer.from(processInstanceId, "utf8")],
    });
    await assert.rejects(repository.get(processInstanceId), {
      name: "FlowNodeOccurrenceStoredValueError",
    });
  });

  async function prepareExecution() {
    const processes = new PostgresqlProcessInstanceRepository(runtime);
    const ordinal = await processes.recordConfirmed({
      instance: registration.instance,
      locator: registration.locator,
    });
    const repository = new PostgresqlExecutionPublicationRepository(runtime);
    await repository.applyPage({ ...registration, ordinal }, firstPage());
    return {
      repository,
      processInstanceId: registration.instance.processInstanceId,
    };
  }

  async function prepareOccurrence() {
    const processes = new PostgresqlProcessInstanceRepository(runtime);
    const ordinal = await processes.recordConfirmed({
      instance: occurrenceRegistration.instance,
      locator: occurrenceRegistration.locator,
    });
    const exactRegistration = { ...occurrenceRegistration, ordinal };
    const executions = new PostgresqlExecutionPublicationRepository(runtime);
    await executions.applyPage(exactRegistration, firstPage());
    const repository = new PostgresqlFlowNodeOccurrenceRepository(runtime);
    await repository.applyPage(exactRegistration, occurrenceFirstPage());
    await executions.applyPage(exactRegistration, secondPage());
    await repository.applyPage(exactRegistration, occurrenceSecondPage());
    return {
      repository,
      processInstanceId: occurrenceRegistration.instance.processInstanceId,
    };
  }
}
